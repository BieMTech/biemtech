/* ── Core functions ────────────────────────────────────── */

/**
 * Apply a language to the current page.
 * Updates all [data-i18n] elements and sets RTL for Arabic.
 */
function applyLang(lang) {
  const dict = I18N[lang] || I18N.en;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });
  /* RTL support */
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.documentElement.lang = lang;
  /* Sync select */
  const sel = document.getElementById("lang-select");
  if (sel) sel.value = lang;
}

/**
 * Save language choice and apply it.
 */
function setLang(lang) {
  if (!I18N[lang]) lang = "en";
  try {
    localStorage.setItem("site_lang", lang);
  } catch (_) {}
  applyLang(lang);
}

/* ── Auto-init ─────────────────────────────────────────── */
(function () {
  /* Detect preferred language */
  let lang = "en";
  try {
    lang = localStorage.getItem("site_lang") || "en";
  } catch (_) {}
  if (!I18N[lang]) {
    /* Try browser language */
    const bl = (navigator.language || "en").slice(0, 2).toLowerCase();
    lang = I18N[bl] ? bl : "en";
  }
  /* Wait for DOM then apply */
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applyLang(lang));
  } else {
    applyLang(lang);
  }
})();
